#ifndef S21_DECIMAL_H
#define S21_DECIMAL_H

#include <stdio.h>
#include <stdint.h>

/**
 * @brief s21_decimal представляет 128-битное десятичное число.
 *
 * Структура содержит:
 * - bits[0], bits[1], bits[2] — 96 бит мантиссы (целая часть числа)
 * - bits[3] — знак и масштаб:
 *     - Бит 31: Знак (0 = положительный, 1 = отрицательный)
 *     - Биты 16–23: Масштаб (количество знаков после запятой, диапазон [0, 28])
 *     - Остальные биты должны быть равны нулю
 */
typedef struct {
    int bits[4];
} s21_decimal;

/* ========================================================================= */
/*                             РАБОТА С БИТАМИ                              */
/* ========================================================================= */

/**
 * @brief Получает значение определённого бита в числе.
 * @param value Число, из которого считывается бит.
 * @param bit_pos Позиция бита (0 до 95 для мантиссы, или до 127).
 * @return Значение бита (0 или 1).
 */
int s21_get_bit(s21_decimal value, int bit_pos);

/**
 * @brief Устанавливает конкретный бит в 0 или 1.
 * @param value Указатель на число, в котором будет установлен бит.
 * @param bit_pos Позиция бита (0 до 127).
 * @param bit_value Значение бита (0 или 1).
 */
void s21_set_bit(s21_decimal *value, int bit_pos, int bit_value);

/* ========================================================================= */
/*                               СДВИГИ БИТОВ                               */
/* ========================================================================= */

/**
 * @brief Выполняет сдвиг мантиссы влево на заданное количество бит.
 * @param value Указатель на число, которое нужно сдвинуть.
 * @param shift Количество бит для сдвига (должно быть от 0 до 32).
 * @return 1, если произошло переполнение, иначе 0.
 */
int s21_shift_left(s21_decimal *value, int shift);

/**
 * @brief Выполняет сдвиг мантиссы вправо на заданное количество бит.
 * @param value Указатель на число, которое нужно сдвинуть.
 * @param shift Количество бит для сдвига (должно быть от 0 до 32).
 * @return 1, если произошло усечение (underflow), иначе 0.
 */
int s21_shift_right(s21_decimal *value, int shift);

/* ========================================================================= */
/*                                  МАСШТАБ                                 */
/* ========================================================================= */

/**
 * @brief Умножает мантиссу на 10^power и увеличивает масштаб.
 * @param value Указатель на число, которое нужно увеличить.
 * @param power Степень, в которую возводится 10 (например, 2 → умножить на 100).
 * @return 1 при ошибке (переполнение или масштаб больше 28), иначе 0.
 */
int s21_scale_up(s21_decimal *value, int power);

/**
 * @brief Делит мантиссу на 10^power и уменьшает масштаб.
 * @param value Указатель на число, которое нужно уменьшить.
 * @param power Степень, в которую возводится 10 (например, 2 → разделить на 100).
 * @return 1 при ошибке (масштаб становится меньше 0), иначе 0.
 */
int s21_scale_down(s21_decimal *value, int power);

/* ========================================================================= */
/*                                 УТИЛИТЫ                                  */
/* ========================================================================= */

/**
 * @brief Возвращает знак числа.
 * @param value Число для проверки.
 * @return 1, если число отрицательное, иначе 0.
 */
int s21_get_sign(s21_decimal value);

/**
 * @brief Устанавливает знак числа.
 * @param value Указатель на число.
 * @param sign 0 — положительное, 1 — отрицательное.
 */
void s21_set_sign(s21_decimal *value, int sign);

/**
 * @brief Возвращает текущий масштаб (количество знаков после запятой).
 * @param value Число для проверки.
 * @return Масштаб в диапазоне [0, 28].
 */
int s21_get_scale(s21_decimal value);

/**
 * @brief Устанавливает масштаб числа.
 * @param value Указатель на число.
 * @param scale Новое значение масштаба (должно быть в диапазоне [0, 28]).
 */
void s21_set_scale(s21_decimal *value, int new_scale);

/**
 * @brief Обнуляет все биты числа (устанавливает его в ноль).
 * @param value Указатель на число, которое нужно обнулить.
 */
void s21_clear_decimal(s21_decimal *value);

/**
 * @brief Копирует одно число типа s21_decimal в другое.
 * @param src Исходное число.
 * @param dst Целевое число.
 */
void s21_copy_decimal(s21_decimal src, s21_decimal *dst);

/**
 * @brief Проверяет, является ли число нулём.
 * @param value Число для проверки.
 * @return 1, если число равно нулю, иначе 0.
 */
int s21_check_zero(s21_decimal value);

/**
 * @brief Умножает число на 10, увеличивая масштаб на 1.
 * @param value Указатель на число, которое нужно умножить.
 */
void s21_mul_10(s21_decimal *value);

/**
 * @brief Делит число на 10, уменьшая масштаб на 1.
 * @param value Указатель на число, которое нужно разделить.
 */
void s21_div_10(s21_decimal *value);

/* ========================================================================= */
/*                                 СРАВНЕНИЕ                                 */
/* ========================================================================= */

/**
 * @brief Сравнивает два числа типа s21_decimal.
 * @param value_1 Первое число для сравнения.
 * @param value_2 Второе число для сравнения.
 * @return 1, если value_1 меньше value_2, иначе 0.
 */
int s21_is_less(s21_decimal value_1, s21_decimal value_2);

/**
 * @brief Сравнивает два числа типа s21_decimal.
 * @param value_1 Первое число для сравнения.
 * @param value_2 Второе число для сравнения.
 * @return 1, если value_1 меньше или равно value_2, иначе 0.
 */
int s21_is_less_or_equal(s21_decimal value_1, s21_decimal value_2);

/**
 * @brief Сравнивает два числа типа s21_decimal.
 * @param value_1 Первое число для сравнения.
 * @param value_2 Второе число для сравнения.
 * @return 1, если value_1 больше value_2, иначе 0.
 */
int s21_is_greater(s21_decimal value_1, s21_decimal value_2);

/**
 * @brief Сравнивает два числа типа s21_decimal.
 * @param value_1 Первое число для сравнения.
 * @param value_2 Второе число для сравнения.
 * @return 1, если value_1 больше или равно value_2, иначе 0.
 */
int s21_is_greater_or_equal(s21_decimal value_1, s21_decimal value_2);

/**
 * @brief Проверяет, равны ли два числа типа s21_decimal.
 * @param value_1 Первое число для сравнения.
 * @param value_2 Второе число для сравнения.
 * @return 1, если числа равны, иначе 0.
 */
int s21_is_equal(s21_decimal value_1, s21_decimal value_2);

/**
 * @brief Проверяет, не равны ли два числа типа s21_decimal.
 * @param value_1 Первое число для сравнения.
 * @param value_2 Второе число для сравнения.
 * @return 1, если числа не равны, иначе 0.
 */
int s21_is_not_equal(s21_decimal value_1, s21_decimal value_2);

#endif  // S21_DECIMAL_H